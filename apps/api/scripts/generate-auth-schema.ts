/**
 * Generates packages/db/src/schema/auth.ts from Better Auth's own schema
 * definition for our plugin set (src/auth/auth.plugins.ts).
 *
 *   pnpm --filter api auth:generate && pnpm db:generate
 */
import { writeFileSync } from "node:fs"
import { resolve } from "node:path"

import { getSchema } from "better-auth/db"

import {
  AUTH_ADVANCED_DATABASE,
  buildAuthPlugins,
} from "../src/auth/auth.plugins.js"

type Field = {
  type: string | string[]
  required?: boolean
  unique?: boolean
  defaultValue?: unknown
  index?: boolean
  references?: { model: string; field: string; onDelete?: string }
}

const noop = async () => {}
const tables = getSchema({
  plugins: buildAuthPlugins({
    webUrl: "",
    sendEmail: noop,
    onWorkspaceCreated: noop,
    onMemberAdded: noop,
    onInvitationAccepted: noop,
  }),
  advanced: { database: AUTH_ADVANCED_DATABASE },
} as never) as Record<string, { fields: Record<string, Field>; order?: number }>

const snake = (s: string) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)
const imports = new Set(["pgTable", "uuid", "index"])

function column(name: string, f: Field): string {
  let col: string
  if (f.references) {
    col = "uuid()"
  } else if (f.type === "string") {
    col = "text()"
    imports.add("text")
  } else if (f.type === "boolean") {
    col = "boolean()"
    imports.add("boolean")
  } else if (f.type === "date") {
    col = "timestamp({ withTimezone: true })"
    imports.add("timestamp")
  } else if (f.type === "number") {
    col = "integer()"
    imports.add("integer")
  } else if (f.type === "json") {
    col = "jsonb()"
    imports.add("jsonb")
  } else if (Array.isArray(f.type) || f.type === "string[]") {
    col = "text().array()"
    imports.add("text")
  } else {
    throw new Error(
      `Unsupported Better Auth field type for ${name}: ${String(f.type)}`
    )
  }
  if (f.required) col += ".notNull()"
  if (f.unique) col += ".unique()"
  if (f.defaultValue !== undefined && typeof f.defaultValue !== "function") {
    col += `.default(${JSON.stringify(f.defaultValue)})`
  } else if (
    f.type === "date" &&
    (name === "createdAt" || name === "updatedAt")
  ) {
    col += ".defaultNow()"
  }
  if (name === "updatedAt") col += ".$onUpdate(() => new Date())"
  if (f.references) {
    const onDelete = f.references.onDelete ?? "cascade"
    col += `.references(() => ${f.references.model}.${f.references.field}, { onDelete: "${onDelete}" })`
  }
  return `  ${name}: ${col},`
}

const ordered = Object.entries(tables).sort(
  ([, a], [, b]) => (a.order ?? 99) - (b.order ?? 99)
)

const body = ordered
  .map(([model, t]) => {
    const cols = Object.entries(t.fields).map(([n, f]) => column(n, f))
    const indexed = Object.entries(t.fields).filter(
      ([, f]) => f.index || f.references
    )
    const idx = indexed.length
      ? `,\n  (t) => [${indexed.map(([n]) => `index().on(t.${n})`).join(", ")}]`
      : ""
    return `export const ${model} = pgTable(\n  "${snake(model)}",\n  {\n  id: uuid().primaryKey().defaultRandom(),\n${cols.join("\n")}\n  }${idx}\n)`
  })
  .join("\n\n")

const header = `/**
 * GENERATED by apps/api/scripts/generate-auth-schema.ts — do not edit by hand.
 * Better Auth tables. Billleaf: \`organization\` == workspace.
 */
import { ${[...imports].sort().join(", ")} } from "drizzle-orm/pg-core"
`
const out = resolve(
  import.meta.dirname,
  "../../../packages/db/src/schema/auth.ts"
)
writeFileSync(out, `${header}\n${body}\n`)
console.log(`✔ wrote ${out}`)
