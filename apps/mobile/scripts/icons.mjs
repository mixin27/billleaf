const out = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/components/ui/icon-data.ts"
)
const body = Object.entries(ICONS)
  .map(([name, source]) => {
    const icon = hugeicons[source]
    if (!icon) throw new Error(`No Hugeicon called ${source}`)
    const clean = icon.map(([tag, attrs]) => [
      tag,
      Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== "key")),
    ])
    return `  ${name}: ${JSON.stringify(clean)},`
  })
  .join("\n")
fs.writeFileSync(
  out,
  `// Generated by scripts/icons.mjs from @hugeicons/core-free-icons. Don't edit.\n` +
    `export const ICON_DATA = {\n${body}\n} as const\n\n` +
    `export type IconName = keyof typeof ICON_DATA\n`
)
console.log(
  `${Object.keys(ICONS).length} icons → ${path.relative(process.cwd(), out)}`
)
