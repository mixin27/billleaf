/**
 * Builds the Billleaf brand files from the mark SVGs in src/svg:
 * - outlines the "billleaf" wordmark (Inter 500) to a path, so it renders
 *   the same everywhere (emails, PNGs, apps without Inter);
 * - writes wordmark/lockup SVGs and src/paths.ts (for the React Logo);
 * - rasterises icons and images for web, email and mobile into assets/,
 *   and copies the ones frameworks expect into the apps.
 *
 * Run: pnpm --filter @workspace/brand assets   (outputs are committed)
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import opentype from "opentype.js"
import sharp from "sharp"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const svgDir = resolve(root, "src/svg")
const out = resolve(root, "assets")
mkdirSync(out, { recursive: true })

const INK = "#142B2B"
const TILE_BG = "#FFFFFF"

// ── Wordmark ──────────────────────────────────────────────

const require = createRequire(import.meta.url)
const buf = readFileSync(
  require.resolve("@fontsource/inter/files/inter-latin-500-normal.woff")
)
const font = opentype.parse(
  buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)
)
const SIZE = 100

/**
 * Lay the word out glyph by glyph (opentype.js can't run Inter's contextual
 * substitution tables, and "billleaf" needs none of them), with kerning.
 */
function layout(text: string, x0: number, y0: number) {
  const scale = SIZE / font.unitsPerEm
  const path = new opentype.Path()
  let x = x0
  let prev: opentype.Glyph | null = null
  for (const ch of text) {
    const g = font.charToGlyph(ch)
    if (prev) x += font.getKerningValue(prev, g) * scale
    path.extend(g.getPath(x, y0, SIZE))
    x += (g.advanceWidth ?? 0) * scale
    prev = g
  }
  return path
}
const box = layout("billleaf", 0, 0).getBoundingBox()
const wordPath = layout("billleaf", -box.x1, -box.y1).toPathData(2)
const wordW = Math.ceil(box.x2 - box.x1)
const wordH = Math.ceil(box.y2 - box.y1)

const read = (name: string) => readFileSync(resolve(svgDir, name), "utf8")
const viewBoxOf = (svg: string) => /viewBox="([^"]+)"/.exec(svg)![1]!
const bodyOf = (svg: string) =>
  svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>.*?<\/title>/, "")

/** Place an SVG (its own viewBox) inside a box in another SVG. */
const place = (svg: string, x: number, y: number, size: number) =>
  `<svg x="${x}" y="${y}" width="${size}" height="${size}" viewBox="${viewBoxOf(svg)}">${bodyOf(svg)}</svg>`

const mark = read("mark.svg")
const markSmall = read("mark-small.svg")

writeFileSync(
  resolve(svgDir, "wordmark.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${wordW} ${wordH}" width="${wordW}" height="${wordH}"><title>billleaf</title><path d="${wordPath}" fill="currentColor"/></svg>\n`
)

/** Mark (1.5 × the wordmark's height) + gap + wordmark. */
function lockup(ink: string) {
  const markSize = Math.round(wordH * 1.5)
  const gap = Math.round(wordH * 0.28)
  const w = markSize + gap + wordW
  const h = markSize
  const wy = Math.round((h - wordH) / 2)
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"><title>billleaf</title>${place(mark, 0, 0, markSize)}<path transform="translate(${markSize + gap} ${wy})" d="${wordPath}" fill="${ink}"/></svg>\n`
}
writeFileSync(resolve(svgDir, "lockup.svg"), lockup(INK))
writeFileSync(resolve(svgDir, "lockup-dark.svg"), lockup("#FFFFFF"))

writeFileSync(
  resolve(root, "src/paths.ts"),
  `// Generated by scripts/build-assets.ts — do not edit.
export const WORDMARK = { d: ${JSON.stringify(wordPath)}, width: ${wordW}, height: ${wordH} } as const
`
)

// ── Raster assets ─────────────────────────────────────────

const svgDoc = (w: number, h: number, inner: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">${inner}</svg>`

const png = (svg: string, w: number, h = w) =>
  sharp(Buffer.from(svg), { density: 300 })
    .resize(w, h)
    .png({ compressionLevel: 9 })
    .toBuffer()

/** The mark alone, transparent. */
const bare = (size: number, small = false) =>
  svgDoc(size, size, place(small ? markSmall : mark, 0, 0, size))

/** The mark on a tile; `scale` is the mark's share of the tile. */
const tile = (size: number, scale: number, radius: number) =>
  svgDoc(
    size,
    size,
    `<rect width="${size}" height="${size}" rx="${radius}" fill="${TILE_BG}"/>${place(mark, (size * (1 - scale)) / 2, (size * (1 - scale)) / 2, size * scale)}`
  )

/** Every drawn pixel white, keeping only the shape (its alpha). */
async function silhouette(svg: string, size: number) {
  const alpha = await sharp(await png(svg, size))
    .ensureAlpha()
    .extractChannel("alpha")
    .toBuffer()
  return sharp({
    create: { width: size, height: size, channels: 3, background: "#FFFFFF" },
  })
    .joinChannel(alpha)
    .png({ compressionLevel: 9 })
    .toBuffer()
}

async function write(name: string, data: Buffer | Promise<Buffer>) {
  writeFileSync(resolve(out, name), await data)
}

/** A .ico holding PNG images (supported by every current browser/OS). */
function ico(images: { size: number; data: Buffer }[]) {
  const header = Buffer.alloc(6)
  header.writeUInt16LE(0, 0)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(images.length, 4)
  const dir = Buffer.alloc(16 * images.length)
  let offset = 6 + dir.length
  images.forEach((img, i) => {
    const o = i * 16
    dir.writeUInt8(img.size >= 256 ? 0 : img.size, o)
    dir.writeUInt8(img.size >= 256 ? 0 : img.size, o + 1)
    dir.writeUInt16LE(1, o + 4)
    dir.writeUInt16LE(32, o + 6)
    dir.writeUInt32LE(img.data.length, o + 8)
    dir.writeUInt32LE(offset, o + 12)
    offset += img.data.length
  })
  return Buffer.concat([header, dir, ...images.map((i) => i.data)])
}

async function main() {
  // Web: browser tab icons are the bare mark; installable icons sit on a tile.
  writeFileSync(resolve(out, "icon.svg"), mark)
  await write(
    "favicon.ico",
    Promise.all(
      [16, 32, 48].map(async (size) => ({
        size,
        data: await png(bare(size, true), size),
      }))
    ).then(ico)
  )
  await write("apple-touch-icon.png", png(tile(180, 0.72, 0), 180))
  await write("icon-192.png", png(tile(192, 0.72, 42), 192))
  await write("icon-512.png", png(tile(512, 0.72, 112), 512))
  await write("maskable-512.png", png(tile(512, 0.56, 0), 512))

  // Open Graph: the lockup on a soft background, with a tagline.
  const lock = read("lockup.svg")
  const [, , lockW, lockH] = viewBoxOf(lock).split(" ").map(Number) as [
    number,
    number,
    number,
    number,
  ]
  const ogW = 1200
  const ogH = 630
  const lw = 660
  const lh = Math.round((lockH / lockW) * lw)
  await write(
    "og-image.png",
    png(
      svgDoc(
        ogW,
        ogH,
        `<rect width="${ogW}" height="${ogH}" fill="#F3FAF5"/><svg x="${(ogW - lw) / 2}" y="${Math.round((ogH - lh) / 2) - 36}" width="${lw}" height="${lh}" viewBox="0 0 ${lockW} ${lockH}">${bodyOf(lock)}</svg><text x="${ogW / 2}" y="${Math.round((ogH + lh) / 2) + 40}" text-anchor="middle" font-family="Inter, Helvetica, Arial, sans-serif" font-size="30" fill="${INK}" opacity="0.75">Quotes, contracts, time, invoices and payments in one place</text>`
      ),
      ogW,
      ogH
    )
  )

  // Email header: lockup at 2× for a 160-wide display.
  await write(
    "email-logo.png",
    png(lock, 320, Math.round((lockH / lockW) * 320))
  )

  // Mobile (Expo): icon on a white square, adaptive foreground in the safe
  // zone (background colour: white), splash mark.
  await write("app-icon-1024.png", png(tile(1024, 0.7, 0), 1024))
  await write(
    "adaptive-foreground-1024.png",
    png(svgDoc(1024, 1024, place(mark, 272, 272, 480)), 1024)
  )
  await write("splash-icon.png", png(bare(512), 512))
  // Android status bar icon: a white silhouette on transparent (the
  // system tints it).
  await write("notification-icon-96.png", silhouette(bare(96, true), 96))

  sync()
  console.log(`✔ brand assets written to ${out} and copied to the apps`)
}

/**
 * Copy into the places frameworks expect them (Next file-based metadata
 * and /public). Paths are relative to the repo root.
 */
function sync() {
  const repo = resolve(root, "../..")
  const copies: [string, string][] = [
    ["icon.svg", "apps/web/app/icon.svg"],
    ["favicon.ico", "apps/web/app/favicon.ico"],
    ["apple-touch-icon.png", "apps/web/app/apple-icon.png"],
    ["og-image.png", "apps/web/app/opengraph-image.png"],
    ["icon-192.png", "apps/web/public/brand/icon-192.png"],
    ["icon-512.png", "apps/web/public/brand/icon-512.png"],
    ["maskable-512.png", "apps/web/public/brand/maskable-512.png"],
    ["email-logo.png", "apps/web/public/brand/email-logo.png"],
    ["icon.svg", "apps/docs/app/icon.svg"],
    ["favicon.ico", "apps/docs/app/favicon.ico"],
    ["apple-touch-icon.png", "apps/docs/app/apple-icon.png"],
    ["og-image.png", "apps/docs/app/opengraph-image.png"],
  ]
  for (const [from, to] of copies) {
    const dest = resolve(repo, to)
    const app = resolve(repo, to.split("/").slice(0, 2).join("/"))
    if (!existsSync(app)) continue // app not created yet
    mkdirSync(dirname(dest), { recursive: true })
    copyFileSync(resolve(out, from), dest)
  }
}

await main()
